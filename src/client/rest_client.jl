# Client-first REST API
#
# Every REST endpoint is implemented as `f(rl::RateLimiter, args...; token, kwargs...)`.
# That is the low-level layer. The public API takes the `Client` instead:
#
#     Accord.get_guild_member(client, guild_id, user_id)
#
# The methods below forward `f(client, args...; kwargs...)` to the low-level
# method with the client's rate limiter and token. Endpoints that already have a
# hand-written `Client` method (create_message, get_channel, …) are skipped.

